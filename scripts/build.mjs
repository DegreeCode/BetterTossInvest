export function readVersion(metadata) {
  const versions = [...metadata.matchAll(/^\/\/\s+@version\s+(\S+)\s*$/gm)];
  const version = versions[0]?.[1];
  if (versions.length !== 1 || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version ?? "")) {
    throw new Error("src/metadata.txt must contain one @version in MAJOR.MINOR.PATCH format.");
  }
  return version;
}

export function validateReleaseTag(tag, version) {
  if (tag !== `v${version}`) {
    throw new Error(`Release tag ${JSON.stringify(tag)} does not match @version ${version}; expected v${version}.`);
  }
}

export async function build({
  outputDirectory = fileURLToPath(new URL("dist/", root)),
  check = false,
  tag,
} = {}) {
  const metadata = (await readFile(new URL("src/metadata.txt", root), "utf8")).trimEnd() + "\n";
  const version = readVersion(metadata);
  if (tag !== undefined) validateReleaseTag(tag, version);
  const sections = await Promise.all(sources.map(async (path) => {
    const source = await readFile(new URL(`src/${path}`, root), "utf8");
    const indented = source.trimEnd().split("\n").map((line) => line ? `  ${line}` : "").join("\n");
    return `  // Source: src/${path}\n${indented}`;
  }));
  const output = `${metadata}// Generated by scripts/build.mjs. Edit src/ and rebuild.\n(() => {\n  "use strict";\n  const VERSION = ${JSON.stringify(version)};\n\n${sections.join("\n\n")}\n})();\n`;
  const files = {
    "BetterTossInvest.user.js": output,
    "BetterTossInvest.meta.js": metadata,
  };

  // Validate the whole private scope before writing either release asset.
  new Script(output, { filename: "BetterTossInvest.user.js" });
  if (!check) await mkdir(outputDirectory, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const target = join(outputDirectory, name);
    if (check) {
      const current = await readFile(target, "utf8").catch((error) => {
        if (error.code !== "ENOENT") throw error;
        return null;
      });
      if (current !== content) throw new Error(`${target} is missing or out of date. Run: node scripts/build.mjs`);
    } else {
      await writeFile(target, content);
    }
  }
  return { version, outputDirectory };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
      throw new Error("Usage: node scripts/build.mjs [--check]");
    }
    const check = args[0] === "--check";
    const { version } = await build({ check });
    console.log(`${check ? "Verified" : "Built"} dist/ release files (${version}).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
